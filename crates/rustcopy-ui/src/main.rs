//! rustcopy console (Slint).
//!
//! Every decision about a backup stays in `robocopy_ingest::{runner, gui_api, sessions}`: this crate
//! only collects a choice, asks the core to plan it, starts the same CLI a scheduled task would, and
//! shows what the core reports. The behaviours it must keep are in CATALOGO_COMPORTAMENTI_GUI.md.
//!
//! One entity, the "lavoro" (SPEC_GUI_SLINT.md 5.0): every copy started here is a session in the
//! core's sessions log, listed in the sidebar with how it went. A row opens its detail, from which it
//! can be repeated or saved as a task.
