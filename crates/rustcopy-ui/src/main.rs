/// Names the mutex and the pipe of the single window (E12).
const INSTANCE_TAG: &str = "rustcopy-ui";
/// How many lavori the sidebar shows.
const LIST_LIMIT: usize = 100;

/// Everything the callbacks share. Lives on the UI thread only.
struct Ctx {
    log: SessionLog,
    slot: RunSlot<ActiveRun>,
    /// The session this window is running now, if any (the core needs it to tell "running" from
    /// "interrupted").
    running_id: RefCell<Option<String>>,
    /// Whether to open the destination folder when the run now going ends clean. A choice about
    /// this run only: it is not part of a copy's settings, so it is not saved with a task.
    open_when_done: Cell<bool>,
    sessions: RefCell<Vec<SessionSummary>>,
    /// Discards a slow report read when the user has opened another lavoro meanwhile (E01).
    details: Generation,
    /// Discards a slow scheduled-task lookup if the list was rebuilt meanwhile.
    schedules: Generation,
    /// Recent throughput samples for the speed chart (MB/s), newest last.
    speeds: RefCell<Vec<f64>>,
    /// The configuration being edited, if the editor is open.
    edit: RefCell<Option<EditState>>,
}

/// What the editor holds between opening a task and saving a proposal.
struct EditState {
    config: PathBuf,
    drafts: Vec<JobDraft>,
    index: usize,
}

fn set_sources(ui: &AppWindow, sources: &[String]) {
    let model: Vec<SharedString> = sources
        .iter()
        .map(|s| SharedString::from(s.as_str()))
        .collect();
    ui.set_sources(ModelRc::new(VecModel::from(model)));
}

/// Adds a folder to the list unless it is already there (case-insensitive, as Windows paths are).
fn push_unique(list: &mut Vec<String>, path: &Path) {
    let text = path.to_string_lossy().into_owned();
    if !list.iter().any(|known| known.eq_ignore_ascii_case(&text)) {
        list.push(text);
    }
}

/// The interface's number for a state (`sessions.slint` documents the mapping).
fn state_number(state: SessionState) -> i32 {
    match state {
        SessionState::Clean => 0,
        SessionState::DryRun => 1,
        SessionState::NeedsLook => 2,
        SessionState::Interrupted => 3,
        SessionState::Running => 4,
    }
}

fn row_for(session: &SessionSummary) -> SessionRow {
    SessionRow {
        id: session.id.as_str().into(),
        sources: format::folder_names(&session.sources).into(),
        dest_name: format::folder_name(&session.dest).into(),
        when: format::when_short(session.started_at).into(),
        files: session.files_copied.to_string().into(),
        size: format::human_bytes(session.bytes_copied).into(),
        state: state_number(session.state),
        saved: session.saved_as.is_some(),
    }
}

/// Rereads the list from the core and shows it; refreshes the open detail too, because a lavoro
/// that was running may just have ended.
fn refresh(ui: &AppWindow, ctx: &Rc<Ctx>) {
    let running = ctx.running_id.borrow().clone();
    let list = ctx.log.list(LIST_LIMIT, running.as_deref());
    let rows: Vec<SessionRow> = list.iter().map(row_for).collect();
    ui.set_sessions(ModelRc::new(VecModel::from(rows)));
    *ctx.sessions.borrow_mut() = list;
    refresh_tasks(ui, ctx);
    if ui.get_page() == 1 {
        let id = ui.get_selected_id().to_string();
        fill_detail(ui, ctx, &id);
    }
}

/// Rereads the saved tasks and pairs each with how its latest run from this console went.
fn refresh_tasks(ui: &AppWindow, ctx: &Rc<Ctx>) {
    let sessions = ctx.sessions.borrow();
    let rows: Vec<TaskRow> = ctx
        .log
        .list_entries(&tasks_dir())
        .into_iter()
        .map(|task| {
            let last = sessions
                .iter()
                .find(|s| s.task.as_deref() == Some(task.path.as_path()));
            TaskRow {
                path: task.path.to_string_lossy().into_owned().into(),
                name: task.name.as_str().into(),
                folders: format!("{}  →  {}", format::folder_names(&task.sources), task.dest)
                    .into(),
                last_state: last.map_or(-1, |s| state_number(s.state)),
                last_when: last
                    .map(|s| format::when_short(s.started_at))
                    .unwrap_or_default()
                    .into(),
                verify: task.verify.map_or("", algorithm_name).into(),
                jobs: i32::try_from(task.jobs).unwrap_or(1),
                saved: task.saved,
                scheduled: false,
            }
        })
        .collect();
    let paths: Vec<PathBuf> = rows
        .iter()
        .map(|row| PathBuf::from(row.path.as_str()))
        .collect();
    ui.set_tasks(ModelRc::new(VecModel::from(rows)));

    // Which of them a Windows scheduled task already runs: asked of `schtasks.exe` on a worker thread
    // (it is slow), and shown when it answers, unless the list was rebuilt meanwhile.
    let ticket = ctx.schedules.next();
    let generation = ctx.schedules.clone();
    let weak = ui.as_weak();
    std::thread::spawn(move || {
        let scheduled: Vec<bool> = paths
            .iter()
            .map(|path| {
                gui_api::schedules_referencing(path)
                    .map(|names| !names.is_empty())
                    .unwrap_or(false)
            })
            .collect();
        let _ = weak.upgrade_in_event_loop(move |ui| {
            if !generation.is_current(ticket) {
                return;
            }
            use slint::Model;
            let model = ui.get_tasks();
            for (index, flag) in scheduled.into_iter().enumerate() {
                if let Some(mut row) = model.row_data(index) {
                    if row.scheduled != flag {
                        row.scheduled = flag;
                        model.set_row_data(index, row);
                    }
                }
            }
        });
    });
}

/// The properties grid for one configuration: every job's settings, grouped, with where each value
/// comes from. All of it is the core's (`gui_api::read_settings`); this only lays it out in rows.
fn property_rows(config: &Path) -> Result<Vec<PropRow>, String> {
    use robocopy_ingest::gui_api::SettingOrigin;
    let jobs = gui_api::read_settings(config).map_err(|e| e.to_string())?;
    let many = jobs.len() > 1;
    let mut rows = Vec::new();
    for job in jobs {
        if many {
            rows.push(PropRow {
                kind: 0,
                key: job.name.as_str().into(),
                value: "".into(),
                origin: 0,
                caution: "".into(),
            });
        }
        for group in job.groups {
            rows.push(PropRow {
                kind: 1,
                key: group.title.as_str().into(),
                value: "".into(),
                origin: 0,
                caution: "".into(),
            });
            for entry in group.entries {
                rows.push(PropRow {
                    kind: 2,
                    key: entry.key.as_str().into(),
                    value: entry.value.as_str().into(),
                    origin: match entry.origin {
                        SettingOrigin::Job => 0,
                        SettingOrigin::Inherited => 1,
                        SettingOrigin::Default => 2,
                    },
                    caution: entry.caution.unwrap_or_default().into(),
                });
            }
        }
    }
    Ok(rows)
}

